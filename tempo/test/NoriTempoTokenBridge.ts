  describe("mint", () => {
    /** A batch of two deposits, for `recipient` and `other`, planted at index 0. */
    async function deployWithDeposits(lockedForRecipient = 1_500_000n) {
      const fixture = await deployBridge();
      const { bridge, recipient, other } = fixture;
      const deposit = (address: string, value: bigint): Request => ({
        target: TEST_ETH_TOKEN_BRIDGE_ADDRESS,
        collectionKeysCount: 1,
        collectionKeys: [ethers.sha256(address), ethers.ZeroHash],
        value,
      });
      const requests = [deposit(recipient.address, lockedForRecipient), deposit(other.address, 2_000_000n)];
      const leaves = requests.map(leafHash);
      const root = node(leaves[0], leaves[1]);
      await plantProofQueueBatches(await bridge.getAddress(), [
        { root, inputQueueCursor: 0n, outputQueueCursor: 2n, outputBlockNumber: 100n },
      ]);
      const witness = (index: number) => ({ path: [leaves[1 - index]], index: BigInt(index), value: requests[index] });
      return { ...fixture, requests, leaves, root, witness };
    }

    it("mints the locked amount of the TIP-20 to the committed recipient", async () => {
      const { bridge, token, recipient, root, witness } = await deployWithDeposits();
      await expect(bridge.connect(recipient).mint(witness(0), 0n))
        .to.emit(bridge, "MintApplied")
        .withArgs(recipient.address, root, 1_500_000n, 1_500_000n);
      expect(await token.balanceOf(recipient.address)).to.equal(1_500_000n);
      expect(await bridge.mintedSoFar(recipient.address)).to.equal(1_500_000n);
    });

    it("resolves both witnesses to the committed root", async () => {
      const { bridge, root, witness } = await deployWithDeposits();
      expect(await bridge.verifiedRequestWitnessRoot(witness(0))).to.equal(root);
      expect(await bridge.verifiedRequestWitnessRoot(witness(1))).to.equal(root);
    });

    it("mints nothing twice for the same deposit", async () => {
      const { bridge, recipient, witness } = await deployWithDeposits();
      await (await bridge.connect(recipient).mint(witness(0), 0n)).wait();
      await expect(bridge.connect(recipient).mint(witness(0), 0n)).to.be.revertedWithCustomError(bridge, "ZeroMintAmount");
    });

    it("mints only the newly locked amount after a later deposit", async () => {
      const { bridge, token, recipient, root, witness } = await deployWithDeposits();
      await (await bridge.connect(recipient).mint(witness(0), 0n)).wait();
      const more: Request = {
        target: TEST_ETH_TOKEN_BRIDGE_ADDRESS,
        collectionKeysCount: 1,
        collectionKeys: [ethers.sha256(recipient.address), ethers.ZeroHash],
        value: 2_500_000n,
      };
      const sibling = repeat(0x99);
      await plantProofQueueBatches(await bridge.getAddress(), [
        { root, inputQueueCursor: 0n, outputQueueCursor: 2n, outputBlockNumber: 100n },
        { root: node(leafHash(more), sibling), inputQueueCursor: 2n, outputQueueCursor: 4n, outputBlockNumber: 101n },
      ]);
      await (await bridge.connect(recipient).mint({ path: [sibling], index: 0n, value: more }, 1n)).wait();
      expect(await token.balanceOf(recipient.address)).to.equal(2_500_000n);
    });

    it("rejects a claim by anyone but the committed recipient", async () => {
      const { bridge, other, witness } = await deployWithDeposits();
      await expect(bridge.connect(other).mint(witness(0), 0n)).to.be.revertedWithCustomError(bridge, "CommitmentMismatch");
    });

    it("rejects a batch that is not committed", async () => {
      const { bridge, recipient, witness } = await deployWithDeposits();
      await expect(bridge.connect(recipient).mint(witness(0), 1n)).to.be.revertedWithCustomError(
        bridge,
        "ProofQueueBatchNotCommitted"
      );
    });

    it("rejects a witness against another batch's root", async () => {
      const { bridge, recipient, root, witness } = await deployWithDeposits();
      await plantProofQueueBatches(await bridge.getAddress(), [
        { root, inputQueueCursor: 0n, outputQueueCursor: 2n, outputBlockNumber: 100n },
        { root: repeat(0x77), inputQueueCursor: 2n, outputQueueCursor: 3n, outputBlockNumber: 101n },
      ]);
      await expect(bridge.connect(recipient).mint(witness(0), 1n)).to.be.revertedWithCustomError(
        bridge,
        "ProofQueueBatchRootMismatch"
      );
    });

    it("rejects a witness index outside the batch", async () => {
      const { bridge, recipient, requests } = await deployWithDeposits();
      const leaves = [repeat(0xa0), repeat(0xa1), leafHash(requests[0]), repeat(0xa3)];
      const root = node(node(leaves[0], leaves[1]), node(leaves[2], leaves[3]));
      await plantProofQueueBatches(await bridge.getAddress(), [
        { root, inputQueueCursor: 0n, outputQueueCursor: 2n, outputBlockNumber: 100n },
      ]);
      const witness = { path: [leaves[3], node(leaves[0], leaves[1])], index: 2n, value: requests[0] };
      await expect(bridge.connect(recipient).mint(witness, 0n))
        .to.be.revertedWithCustomError(bridge, "WitnessIndexOutsideProofQueueBatch")
        .withArgs(2n, 2n);
    });

    it("rejects a deposit of another contract", async () => {
      const { bridge, recipient } = await deployBridge();
      const foreign: Request = {
        target: "0x" + "33".repeat(20),
        collectionKeysCount: 1,
        collectionKeys: [ethers.sha256(recipient.address), ethers.ZeroHash],
        value: 1_000_000n,
      };
      const sibling = repeat(0x99);
      await plantProofQueueBatches(await bridge.getAddress(), [
        { root: node(leafHash(foreign), sibling), inputQueueCursor: 0n, outputQueueCursor: 2n, outputBlockNumber: 100n },
      ]);
      await expect(
        bridge.connect(recipient).mint({ path: [sibling], index: 0n, value: foreign }, 0n)
      ).to.be.revertedWithCustomError(bridge, "NotTokenBridgeRequest");
    });

    it("rejects a locked amount beyond 64 bits", async () => {
      const { bridge, recipient } = await deployBridge();
      const huge: Request = {
        target: TEST_ETH_TOKEN_BRIDGE_ADDRESS,
        collectionKeysCount: 1,
        collectionKeys: [ethers.sha256(recipient.address), ethers.ZeroHash],
        value: MAX_U64 + 1n,
      };
      const sibling = repeat(0x99);
      await plantProofQueueBatches(await bridge.getAddress(), [
        { root: node(leafHash(huge), sibling), inputQueueCursor: 0n, outputQueueCursor: 2n, outputBlockNumber: 100n },
      ]);
      await expect(
        bridge.connect(recipient).mint({ path: [sibling], index: 0n, value: huge }, 0n)
      ).to.be.revertedWithCustomError(bridge, "LockedAmountOverflow");
    });

    it("rejects a malformed witness", async () => {
      const { bridge, recipient, witness } = await deployWithDeposits();
      const tooDeep = { ...witness(0), path: Array(MAX_TREE_DEPTH + 1).fill(repeat(0x01)) };
      await expect(bridge.connect(recipient).mint(tooDeep, 0n)).to.be.revertedWithCustomError(
        bridge,
        "InvalidDepositWitness"
      );
      const tooManyKeys = {
        ...witness(0),
        value: { ...witness(0).value, collectionKeysCount: MAX_COLLECTION_KEYS + 1 },
      };
      await expect(bridge.connect(recipient).mint(tooManyKeys, 0n)).to.be.revertedWithCustomError(
        bridge,
        "InvalidDepositWitness"
      );
    });
  });

  describe("ERC-20 mirrors", () => {
    /** An Ethereum ERC-20 the mirror stands for; on Tempo it is only a key. */
    const ETH_TOKEN = "0x" + "44".repeat(20);
    const tokenKey = (address: string) => ethers.zeroPadValue(address, 32);

    /** A bridge with a mirror of `ETH_TOKEN` registered by its deployer. */
    async function deployWithMirror() {
      const fixture = await deployBridge();
      const { bridge } = fixture;
      await (await bridge.registerMirror(ETH_TOKEN, "Nori USDC", "nUSDC", "USD", ethers.hexlify(randomBytes(32)))).wait();
      const mirror = ITIP20__factory.connect(await bridge.mirrorOf(ETH_TOKEN), fixture.deployer);
      return { ...fixture, mirror };
    }

    /** Plants batches each holding one request, at indices from 0, and returns each request's witness. */
    async function plantOneRequestBatches(bridgeAddress: string, requests: Request[]) {
      const sibling = repeat(0x99);
      await plantProofQueueBatches(
        bridgeAddress,
        requests.map((request, i) => ({
          root: node(leafHash(request), sibling),
          inputQueueCursor: BigInt(2 * i),
          outputQueueCursor: BigInt(2 * i + 2),
          outputBlockNumber: BigInt(100 + i),
        }))
      );
      return requests.map((value) => ({ path: [sibling], index: 0n, value }));
    }

    const erc20Deposit = (recipient: string, ethToken: string, value: bigint): Request => ({
      target: TEST_ETH_TOKEN_BRIDGE_ADDRESS,
      collectionKeysCount: 2,
      collectionKeys: [ethers.sha256(recipient), tokenKey(ethToken)],
      value,
    });

    const pauseState = (ethToken: string, value: bigint): Request => ({
      target: TEST_ETH_TOKEN_BRIDGE_ADDRESS,
      collectionKeysCount: 2,
      collectionKeys: [PAUSE_KEY, tokenKey(ethToken)],
      value,
    });

    it("keeps PAUSE_KEY and the pause states in step with the contract", async () => {
      const { bridge } = await deployBridge();
      expect(await bridge.PAUSE_KEY()).to.equal(PAUSE_KEY);
      expect(await bridge.PAUSE_STATE_UNPAUSED()).to.equal(PAUSE_STATE_UNPAUSED);
      expect(await bridge.PAUSE_STATE_PAUSED()).to.equal(PAUSE_STATE_PAUSED);
    });

    it("registers one 6-decimal TIP-20 mirror per ERC-20", async () => {
      const { bridge } = await deployBridge();
      await expect(bridge.registerMirror(ETH_TOKEN, "Nori USDC", "nUSDC", "USD", ethers.hexlify(randomBytes(32)))).to.emit(
        bridge,
        "MirrorRegistered"
      );
      const mirror = ITIP20__factory.connect(await bridge.mirrorOf(ETH_TOKEN), ethers.provider);
      expect(await mirror.decimals()).to.equal(TIP20_DECIMALS);
      expect(await mirror.paused()).to.equal(false);
      await expect(
        bridge.registerMirror(ETH_TOKEN, "Nori USDC", "nUSDC", "USD", ethers.hexlify(randomBytes(32)))
      ).to.be.revertedWithCustomError(bridge, "MirrorExists");
    });

    it("rejects registering by anyone but the deployer", async () => {
      const { bridge, other, deployer } = await deployBridge();
      await expect(
        bridge.connect(other).registerMirror(ETH_TOKEN, "Nori USDC", "nUSDC", "USD", ethers.hexlify(randomBytes(32)))
      )
        .to.be.revertedWithCustomError(bridge, "NotMirrorAdmin")
        .withArgs(other.address, deployer.address);
    });

    it("mints the mirror against a proven ERC-20 deposit, only the new amount each time", async () => {
      const { bridge, mirror, recipient } = await deployWithMirror();
      const [first, second] = await plantOneRequestBatches(await bridge.getAddress(), [
        erc20Deposit(recipient.address, ETH_TOKEN, 1_500_000n),
        erc20Deposit(recipient.address, ETH_TOKEN, 2_500_000n),
      ]);
      await expect(bridge.connect(recipient).mintERC20(first, 0n)).to.emit(bridge, "ERC20MintApplied");
      expect(await mirror.balanceOf(recipient.address)).to.equal(1_500_000n);
      await expect(bridge.connect(recipient).mintERC20(first, 0n)).to.be.revertedWithCustomError(bridge, "ZeroMintAmount");
      await (await bridge.connect(recipient).mintERC20(second, 1n)).wait();
      expect(await mirror.balanceOf(recipient.address)).to.equal(2_500_000n);
      expect(await bridge.erc20MintedSoFar(ETH_TOKEN, recipient.address)).to.equal(2_500_000n);
    });

    it("rejects an ERC-20 deposit for a claim by anyone but the committed recipient", async () => {
      const { bridge, recipient, other } = await deployWithMirror();
      const [witness] = await plantOneRequestBatches(await bridge.getAddress(), [
        erc20Deposit(recipient.address, ETH_TOKEN, 1_000_000n),
      ]);
      await expect(bridge.connect(other).mintERC20(witness, 0n)).to.be.revertedWithCustomError(bridge, "CommitmentMismatch");
    });

    it("rejects an ERC-20 deposit of a token with no mirror", async () => {
      const { bridge, recipient } = await deployWithMirror();
      const unmirrored = "0x" + "55".repeat(20);
      const [witness] = await plantOneRequestBatches(await bridge.getAddress(), [
        erc20Deposit(recipient.address, unmirrored, 1_000_000n),
      ]);
      await expect(bridge.connect(recipient).mintERC20(witness, 0n))
        .to.be.revertedWithCustomError(bridge, "NoMirror")
        .withArgs(ethers.getAddress(unmirrored));
    });

    it("rejects an ERC-20 deposit as an ETH mint, and an ETH deposit as an ERC-20 mint", async () => {
      const { bridge, recipient } = await deployWithMirror();
      const ethDeposit: Request = {
        target: TEST_ETH_TOKEN_BRIDGE_ADDRESS,
        collectionKeysCount: 1,
        collectionKeys: [ethers.sha256(recipient.address), ethers.ZeroHash],
        value: 1_000_000n,
      };
      const [erc20Witness, ethWitness] = await plantOneRequestBatches(await bridge.getAddress(), [
        erc20Deposit(recipient.address, ETH_TOKEN, 1_000_000n),
        ethDeposit,
      ]);
      await expect(bridge.connect(recipient).mint(erc20Witness, 0n))
        .to.be.revertedWithCustomError(bridge, "CollectionKeysCountMismatch")
        .withArgs(2, 1);
      await expect(bridge.connect(recipient).mintERC20(ethWitness, 1n))
        .to.be.revertedWithCustomError(bridge, "CollectionKeysCountMismatch")
        .withArgs(1, 2);
    });

    it("rejects a token key wider than an address", async () => {
      const { bridge, recipient } = await deployWithMirror();
      const wide: Request = {
        ...erc20Deposit(recipient.address, ETH_TOKEN, 1_000_000n),
        collectionKeys: [ethers.sha256(recipient.address), repeat(0x44)],
      };
      const [witness] = await plantOneRequestBatches(await bridge.getAddress(), [wide]);
      await expect(bridge.connect(recipient).mintERC20(witness, 0n)).to.be.revertedWithCustomError(bridge, "InvalidTokenKey");
    });

    it("pauses and unpauses the mirror as the proven pause state changes", async () => {
      const { bridge, mirror } = await deployWithMirror();
      const [paused, unpaused] = await plantOneRequestBatches(await bridge.getAddress(), [
        pauseState(ETH_TOKEN, PAUSE_STATE_PAUSED),
        pauseState(ETH_TOKEN, PAUSE_STATE_UNPAUSED),
      ]);
      expect([...(await bridge.lastPauseApplied(ETH_TOKEN))]).to.deep.equal([false, 0n]);

      await expect(bridge.applyPause(paused, 0n))
        .to.emit(bridge, "PauseApplied")
        .withArgs(ethers.getAddress(ETH_TOKEN), await mirror.getAddress(), true, 0n);
      expect(await mirror.paused()).to.equal(true);
      expect([...(await bridge.lastPauseApplied(ETH_TOKEN))]).to.deep.equal([true, 0n]);

      await (await bridge.applyPause(unpaused, 1n)).wait();
      expect(await mirror.paused()).to.equal(false);
    });

    it("keeps a paused mirror's holders from moving it", async () => {
      const { bridge, mirror, recipient, other } = await deployWithMirror();
      const [deposit, paused] = await plantOneRequestBatches(await bridge.getAddress(), [
        erc20Deposit(recipient.address, ETH_TOKEN, 1_000_000n),
        pauseState(ETH_TOKEN, PAUSE_STATE_PAUSED),
      ]);
      await (await bridge.connect(recipient).mintERC20(deposit, 0n)).wait();
      await (await bridge.applyPause(paused, 1n)).wait();
      const transfer = new ethers.Contract(
        await mirror.getAddress(),
        ["function transfer(address to, uint256 amount) returns (bool)"],
        recipient
      );
      await expect(transfer.transfer(other.address, 1n)).to.be.revert(ethers);
      expect(await mirror.balanceOf(other.address)).to.equal(0n);
    });

    it("rejects a pause state from a batch no newer than the last one applied", async () => {
      const { bridge } = await deployWithMirror();
      const [older, newer] = await plantOneRequestBatches(await bridge.getAddress(), [
        pauseState(ETH_TOKEN, PAUSE_STATE_UNPAUSED),
        pauseState(ETH_TOKEN, PAUSE_STATE_PAUSED),
      ]);
      await (await bridge.applyPause(newer, 1n)).wait();
      await expect(bridge.applyPause(older, 0n)).to.be.revertedWithCustomError(bridge, "PauseNotNewer").withArgs(0n, 1n);
      await expect(bridge.applyPause(newer, 1n)).to.be.revertedWithCustomError(bridge, "PauseNotNewer").withArgs(1n, 1n);
    });

    it("rejects an ERC-20 deposit as a pause state, and a pause state other than paused or unpaused", async () => {
      const { bridge, recipient } = await deployWithMirror();
      const [deposit, neither] = await plantOneRequestBatches(await bridge.getAddress(), [
        erc20Deposit(recipient.address, ETH_TOKEN, PAUSE_STATE_PAUSED),
        pauseState(ETH_TOKEN, 3n),
      ]);
      await expect(bridge.applyPause(deposit, 0n)).to.be.revertedWithCustomError(bridge, "NotPauseState");
      await expect(bridge.applyPause(neither, 1n))
        .to.be.revertedWithCustomError(bridge, "InvalidPauseState")
        .withArgs(3n);
    });

    it("counts every mirror unit it mints, across recipients", async () => {
      const { bridge, mirror, recipient, other } = await deployWithMirror();
      const [mine, theirs] = await plantOneRequestBatches(await bridge.getAddress(), [
        erc20Deposit(recipient.address, ETH_TOKEN, 1_500_000n),
        erc20Deposit(other.address, ETH_TOKEN, 700_000n),
      ]);
      await (await bridge.connect(recipient).mintERC20(mine, 0n)).wait();
      await (await bridge.connect(other).mintERC20(theirs, 1n)).wait();
      expect(await bridge.erc20TotalMinted(ETH_TOKEN)).to.equal(2_200_000n);
      expect(await mirror.totalSupply()).to.equal(2_200_000n);
      expect(await bridge.ethTokenOf(await mirror.getAddress())).to.equal(ethers.getAddress(ETH_TOKEN));
    });

    describe("an issuer's own TIP-20 (adoptMirror)", () => {
      const PAUSE_ROLE = ethers.id(PAUSE_ROLE_NAME);
      const UNPAUSE_ROLE = ethers.id(UNPAUSE_ROLE_NAME);
      const DEFAULT_ADMIN_ROLE = ethers.ZeroHash;

      /**
       * The issuer's TIP-20, created through TIP20Factory with the issuer as
       * its admin, and the roles it grants the bridge.
       */
      async function issuerTip20(
        bridgeAddress: string,
        issuer: Awaited<ReturnType<typeof deployBridge>>["other"],
        roles: string[] = [ISSUER_ROLE, PAUSE_ROLE, UNPAUSE_ROLE]
      ) {
        const factory = ITIP20Factory__factory.connect(TIP20_FACTORY_ADDRESS, issuer);
        const args = ["Issuer USD", "iUSD", "USD", PATH_USD_ADDRESS, issuer.address, ethers.hexlify(randomBytes(32))] as const;
        const address = await factory.createToken.staticCall(...args);
        await (await factory.createToken(...args)).wait();
        const tip20 = ITIP20__factory.connect(address, issuer);
        for (const role of roles) await (await tip20.grantRole(role, bridgeAddress)).wait();
        return tip20;
      }

      /** A bridge that adopted the issuer's TIP-20 as the mirror of `ETH_TOKEN`; `other` is the issuer. */
      async function deployWithAdoptedMirror() {
        const fixture = await deployBridge();
        const { bridge, other: issuer } = fixture;
        const mirror = await issuerTip20(await bridge.getAddress(), issuer);
        await (await bridge.adoptMirror(ETH_TOKEN, await mirror.getAddress())).wait();
        return { ...fixture, issuer, mirror };
      }

      it("adopts it, and the issuer stays its admin", async () => {
        const { bridge, other: issuer, deployer } = await deployBridge();
        const tip20 = await issuerTip20(await bridge.getAddress(), issuer);
        await expect(bridge.adoptMirror(ETH_TOKEN, await tip20.getAddress()))
          .to.emit(bridge, "MirrorAdopted")
          .withArgs(ethers.getAddress(ETH_TOKEN), await tip20.getAddress());
        expect(await bridge.mirrorOf(ETH_TOKEN)).to.equal(await tip20.getAddress());
        expect(await bridge.ethTokenOf(await tip20.getAddress())).to.equal(ethers.getAddress(ETH_TOKEN));
        expect(await tip20.hasRole(issuer.address, DEFAULT_ADMIN_ROLE)).to.equal(true);
        expect(await tip20.hasRole(await bridge.getAddress(), DEFAULT_ADMIN_ROLE)).to.equal(false);
        expect(await tip20.hasRole(deployer.address, DEFAULT_ADMIN_ROLE)).to.equal(false);
      });

      it("rejects adopting by anyone but the deployer", async () => {
        const { bridge, other: issuer, deployer } = await deployBridge();
        const tip20 = await issuerTip20(await bridge.getAddress(), issuer);
        await expect(bridge.connect(issuer).adoptMirror(ETH_TOKEN, await tip20.getAddress()))
          .to.be.revertedWithCustomError(bridge, "NotMirrorAdmin")
          .withArgs(issuer.address, deployer.address);
      });

      for (const [name, missing] of [
        ["ISSUER_ROLE", ISSUER_ROLE_NAME],
        ["PAUSE_ROLE", PAUSE_ROLE_NAME],
        ["UNPAUSE_ROLE", UNPAUSE_ROLE_NAME],
      ] as const) {
        it(`rejects a TIP-20 that did not grant the bridge ${name}`, async () => {
          const { bridge, other: issuer } = await deployBridge();
          const roles = [ISSUER_ROLE, PAUSE_ROLE, UNPAUSE_ROLE].filter((role) => role !== ethers.id(missing));
          const tip20 = await issuerTip20(await bridge.getAddress(), issuer, roles);
          await expect(bridge.adoptMirror(ETH_TOKEN, await tip20.getAddress()))
            .to.be.revertedWithCustomError(bridge, "MissingMirrorRole")
            .withArgs(await tip20.getAddress(), ethers.id(missing));
        });
      }

      it("rejects an address that is not a TIP-20, and the bridged nETH", async () => {
        const { bridge, token } = await deployBridge();
        const notTip20 = "0x" + "66".repeat(20);
        await expect(bridge.adoptMirror(ETH_TOKEN, notTip20))
          .to.be.revertedWithCustomError(bridge, "NotTIP20")
          .withArgs(ethers.getAddress(notTip20));
        await expect(bridge.adoptMirror(ETH_TOKEN, await token.getAddress()))
          .to.be.revertedWithCustomError(bridge, "NotTIP20")
          .withArgs(await token.getAddress());
      });

      it("rejects a second mirror of one ERC-20, and one TIP-20 mirroring two ERC-20s", async () => {
        const { bridge, mirror, issuer } = await deployWithAdoptedMirror();
        const another = await issuerTip20(await bridge.getAddress(), issuer);
        await expect(bridge.adoptMirror(ETH_TOKEN, await another.getAddress())).to.be.revertedWithCustomError(
          bridge,
          "MirrorExists"
        );
        await expect(bridge.registerMirror(ETH_TOKEN, "Again", "AGN", "USD", ethers.hexlify(randomBytes(32)))).to.be.revertedWithCustomError(
          bridge,
          "MirrorExists"
        );
        await expect(bridge.adoptMirror("0x" + "55".repeat(20), await mirror.getAddress()))
          .to.be.revertedWithCustomError(bridge, "AlreadyAMirror")
          .withArgs(await mirror.getAddress(), ethers.getAddress(ETH_TOKEN));
      });

      it("mints it against proven deposits and follows the ERC-20's pause, as a created mirror does", async () => {
        const { bridge, mirror, recipient } = await deployWithAdoptedMirror();
        const [deposit, paused, unpaused] = await plantOneRequestBatches(await bridge.getAddress(), [
          erc20Deposit(recipient.address, ETH_TOKEN, 1_000_000n),
          pauseState(ETH_TOKEN, PAUSE_STATE_PAUSED),
          pauseState(ETH_TOKEN, PAUSE_STATE_UNPAUSED),
        ]);
        await expect(bridge.connect(recipient).mintERC20(deposit, 0n)).to.emit(bridge, "ERC20MintApplied");
        expect(await mirror.balanceOf(recipient.address)).to.equal(1_000_000n);
        expect(await bridge.erc20TotalMinted(ETH_TOKEN)).to.equal(1_000_000n);
        await (await bridge.applyPause(paused, 1n)).wait();
        expect(await mirror.paused()).to.equal(true);
        await (await bridge.applyPause(unpaused, 2n)).wait();
        expect(await mirror.paused()).to.equal(false);
      });

      it("leaves a mint the issuer's supply cap refuses to be claimed once the cap allows it", async () => {
        const { bridge, mirror, issuer, recipient } = await deployWithAdoptedMirror();
        const capped = new ethers.Contract(
          await mirror.getAddress(),
          ["function setSupplyCap(uint256 newSupplyCap)"],
          issuer
        );
        await (await capped.setSupplyCap(500_000n)).wait();
        const [deposit] = await plantOneRequestBatches(await bridge.getAddress(), [
          erc20Deposit(recipient.address, ETH_TOKEN, 1_000_000n),
        ]);
        await expect(bridge.connect(recipient).mintERC20(deposit, 0n)).to.be.revert(ethers);
        expect(await bridge.erc20MintedSoFar(ETH_TOKEN, recipient.address)).to.equal(0n);
        await (await capped.setSupplyCap(1_000_000n)).wait();
        await (await bridge.connect(recipient).mintERC20(deposit, 0n)).wait();
        expect(await mirror.balanceOf(recipient.address)).to.equal(1_000_000n);
      });

      it("stops minting once the issuer revokes the bridge's ISSUER_ROLE", async () => {
        const { bridge, mirror, issuer, recipient } = await deployWithAdoptedMirror();
        const revoke = new ethers.Contract(
          await mirror.getAddress(),
          ["function revokeRole(bytes32 role, address account)"],
          issuer
        );
        await (await revoke.revokeRole(ISSUER_ROLE, await bridge.getAddress())).wait();
        const [deposit] = await plantOneRequestBatches(await bridge.getAddress(), [
          erc20Deposit(recipient.address, ETH_TOKEN, 1_000_000n),
        ]);
        await expect(bridge.connect(recipient).mintERC20(deposit, 0n)).to.be.revert(ethers);
        expect(await mirror.totalSupply()).to.equal(0n);
      });
    });
  });
