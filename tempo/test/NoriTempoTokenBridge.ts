const repeat = (byte: number) => "0x" + byte.toString(16).padStart(2, "0").repeat(32);

interface Request {
  target: string;
  collectionKeysCount: number;
  collectionKeys: [string, string];
  value: bigint;
}

/** `requestLeafHash`, in TypeScript, for building batch trees in tests. */
function leafHash(r: Request): string {
  const key0 = ethers.getBytes(r.collectionKeys[0]);
  const key1 = ethers.getBytes(r.collectionKeys[1]);
  const value = ethers.getBytes(ethers.toBeHex(r.value, 32));
  const field = (bytes: Uint8Array) => ethers.concat([bytes.slice(1), new Uint8Array(1)]);
  return ethers.sha256(
    ethers.concat([
      r.target,
      new Uint8Array([r.collectionKeysCount, key0[0], key1[0], value[0]]),
      new Uint8Array(8),
      field(key0),
      field(key1),
      field(value),
    ])
  );
}

const node = (left: string, right: string) => ethers.sha256(ethers.concat([left, right]));

const word = (value: bigint) => ethers.toBeHex(value, 32);

